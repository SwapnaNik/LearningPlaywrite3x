//While loop will not run if the condition is false at the beginning
console.log("While loop");
let a=10;
while(a<10){
    console.log(a);
    a++;
}//OP- While loop

//Do while loop will run at least once even if the condition is false at the beginning  
console.log("Do while loop");
let a1=10;
do{
    console.log(a1);
    a1++;
}while(a1<10);// OP - Do while loop
//10

//do while exceute the code atleast one
