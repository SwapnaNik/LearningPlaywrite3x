//While loop - it is used to execute a block of code as long as a 
// specified condition is true. The while loop will continue 
// to run until the condition evaluates to false.
//ICU 

let attempts = 0; // Initialize a variable -1
while(attempts < 3) // Condition - 2
{   
    console.log("Attempts " + attempts);
    attempts++; // Update the variable - 3
}
//OP- 
// Attempts 0
// Attempts 1
// Attempts 2