//Logical operators are And, Or, Not

/*
&& is the logical AND operator. 
It returns true if both operands are true, 
otherwise it returns false.

|| is the logical OR operator. 
It returns true if at least one of the operands is true, 
otherwise it returns false.

*/

//examples : 

let a = true;
let b = false;

console.log(a && b); // false - both operands are not true
console.log(a || b); // true - at least one operand is true
console.log(!a); // false - negation of true is false


